#!/usr/bin/env node
/**
 * Explicit first-party P0 development pilot. NEVER a source-rights issuer.
 * Produces an unqualified, sealed candidate; never installs/activates a skill.
 */
import {createHash,generateKeyPairSync,sign} from 'node:crypto';
import {resolve,join,isAbsolute} from 'node:path';
import {pathToFileURL} from 'node:url';
import {createRecipeAdapter} from '../src/backend/recipe-adapter.mjs';
import {createComposer,canonicalJSON,writePackage,readPackage,verifyPackage} from '../src/backend/compose.mjs';
import {createSignedAssertionAdapter} from '../src/backend/signed-assertions.mjs';
import {createPinnedPrismGuest} from '../src/backend/prism-guest.mjs';
import {loadFirstPartyPilots,recipeForPilot,PILOT_DEFINITIONS} from '../src/backend/first-party-pilots.mjs';

export const DEV_HOLO_SHA256='9ebac1a33da068be7c1c81bc7652938811936089df5a026b7ce5aee1f8f7ed3e';
const DOMAIN='QORTARA-METHOD-ASSERTION-V1\n';
const SHA=x=>createHash('sha256').update(x).digest('hex');
const OUTPUT_MAX=16_384;
function refuse(code,message){throw Object.assign(new Error(message),{code});}
function devFixtureAssertionAdapter(methodPin){
 // These records are fabricated solely to exercise the verifier and real
 // guest. They DO NOT declare legal permission, real source review or
 // operator authority. No signing key is persisted or checked into Git.
 const {privateKey,publicKey}=generateKeyPairSync('ed25519');
 const keyPem=publicKey.export({type:'spki',format:'pem'}).toString('utf8');
 const keySha=SHA(publicKey.export({type:'spki',format:'der'}));
 const now=Math.floor(Date.now()/1000);
 const facts=['evidence','rights','authority','coverage'];
 const samples=Object.fromEntries(facts.map(k=>[k,Buffer.from(
   'SYNTHETIC ONLY: '+k+' claim for pinned method '+methodPin)]));
 const digests=Object.fromEntries(facts.map(k=>[k,SHA(samples[k])]));
 return createSignedAssertionAdapter({
   trust:{schema:'qortara/method-assertion-trust/1',
     issuer:'fixture.qortara.development',keyId:'ephemeral-test-only',
     publicKeyPem:keyPem,publicKeySha256:keySha,policyRevision:'fixture-only-v1',
     revocations:{validFrom:now-60,expiresAt:now+60,proofDigests:[]}},
   loadEnvelope:async subjectSha256=>{
     const payload={schema:'qortara/method-assertion/1',subjectSha256,
       issuer:'fixture.qortara.development',keyId:'ephemeral-test-only',
       policyRevision:'fixture-only-v1',validFrom:now-30,expiresAt:now+30,
       facts:{evidence:true,rights:true,authority:true,coverage:true},
       evidenceDigests:digests};
     return {schema:'qortara/signed-method-assertion/1',payload,
       signature:sign(null,Buffer.from(DOMAIN+canonicalJSON(payload)),privateKey).toString('base64url')};
   },
   readEvidence:async({sha256,field})=>{
     const data=samples[field];
     if(!data||SHA(data)!==sha256)refuse('FIXTURE_EVIDENCE','unexpected fixture evidence request');
     return data;
   },
   nowEpoch:()=>Math.floor(Date.now()/1000)
 });
}
/**
 * Only trusted local developer invocation may choose this fixture route.
 * No claim of production rights, host behavior, signature key custody or P2.
 */
export async function runFirstPartyPilot({id,holoPath,holoSha256,outputRoot,devP0Fixture,loadRuntime}={}){
 if(devP0Fixture!==true)refuse('FIXTURE_CONSENT','--dev-p0-fixture must be explicit');
 if(!PILOT_DEFINITIONS.some(x=>x.id===id))refuse('PILOT_UNKNOWN','unrecognized original first-party pilot');
 if(typeof holoPath!=='string'||!isAbsolute(holoPath)||
    holoSha256!==DEV_HOLO_SHA256)
   refuse('PILOT_PIN','exact recorded development P0 holo and absolute path required');
 if(typeof outputRoot!=='string'||!isAbsolute(outputRoot)||outputRoot.length>OUTPUT_MAX)
   refuse('OUTPUT_ROOT','explicit absolute, pre-existing output parent required');
 const registry=await loadFirstPartyPilots();
 const recipe=recipeForPilot(id,registry);
 const {plan,methods}=createRecipeAdapter(registry)(recipe);
 const adapter=devFixtureAssertionAdapter(methods[0].sha256);
 const guest=createPinnedPrismGuest({
   holoPath,holoSha256,developmentP0Consent:true,
   ...(loadRuntime?{loadRuntime}:{})
 });
 const packageValue=await createComposer({assertMethod:adapter,runPrism:guest,
   holoSha256})(plan,methods);
 const verified=verifyPackage(packageValue);
 const destination=join(outputRoot,id); // Agent Skills requires folder name = frontmatter name
 await writePackage(packageValue,destination);
 const readBack=await readPackage(destination);
 if(JSON.stringify(packageValue)!==JSON.stringify(readBack))
   refuse('PILOT_REPLAY','sealed local package differs from generated bytes');
 const receipt=JSON.parse(packageValue.files['RECEIPT.json']);
 if(receipt.productionEligible!==false||receipt.hostValidated!==false||
    receipt.modelCallsMeasured!==false)
   refuse('PILOT_SCOPE','development candidate was incorrectly promoted');
 return {schema:'qortara/first-party-pilot-result/1',
   status:'DEVELOPMENT_CANDIDATE',id,
   output:destination,sourceCommit:registry.sourceSnapshot.commit,
   sourceSnapshotSha256:registry.sourceSnapshot.sha256,
   artifactSha256:verified.packageSha256,
   holoSha256,assurance:'P0 unverified',
   sourceLegalRights:'NOT_REVIEWED_FOR_DISTRIBUTION',
   signedEvidence:'SYNTHETIC_EPHEMERAL_TEST_ONLY',
   hostValidated:false,modelCallsMeasured:false,productionEligible:false};
}
export function parseArgs(args){
 if(!Array.isArray(args))refuse('USAGE','arguments must be an array');
 const allowed=new Set(['--id','--holo','--sha256','--output-root']);
 const result={};
 for(let i=0;i<args.length;i++){
   const option=args[i];
   if(option==='--dev-p0-fixture'){
     if(result.devP0Fixture)refuse('USAGE','duplicate development fixture flag');
     result.devP0Fixture=true;continue;
   }
   if(!allowed.has(option)||Object.hasOwn(result,option))
     refuse('USAGE','unexpected or repeated option: '+String(option));
   const value=args[++i];
   if(typeof value!=='string'||value.startsWith('--'))refuse('USAGE','missing '+option);
   result[option]=value;
 }
 if(!result['--id']||!result['--holo']||!result['--sha256']||!result['--output-root']||
    result.devP0Fixture!==true)
   refuse('USAGE','required: --id --holo --sha256 --output-root --dev-p0-fixture');
 return {id:result['--id'],holoPath:result['--holo'],
   holoSha256:result['--sha256'],outputRoot:result['--output-root'],
   devP0Fixture:true};
}
if(process.argv[1]&&pathToFileURL(resolve(process.argv[1])).href===import.meta.url){
 try{
   const result=await runFirstPartyPilot(parseArgs(process.argv.slice(2)));
   process.stdout.write(JSON.stringify(result,null,2)+'\n');
 }catch(err){
   process.stderr.write(JSON.stringify({code:err?.code??'PILOT_ERROR',
     message:err?.message??String(err),productionEligible:false})+'\n');
   process.exitCode=2;
 }
}
