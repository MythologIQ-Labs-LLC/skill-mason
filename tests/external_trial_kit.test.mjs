import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
const sha=x=>createHash('sha256').update(x).digest('hex');
const root=new URL('../trials/ci-failure-triage-v5/',import.meta.url);
const skill=await readFile(new URL('SKILL.md',root),'utf8');
const provenance=await readFile(new URL('README.md',root),'utf8');
const samples=await readFile(new URL('SAMPLE_CASES.md',root),'utf8');
const issueForm=await readFile(new URL('../.github/ISSUE_TEMPLATE/skill-trial-feedback.yml',import.meta.url),'utf8');
const source=await readFile(new URL('../pilots/first-party/ci-failure-triage-v5/procedure.json',import.meta.url),'utf8');

test('external trial SKILL.md matches the actual native P0 generated bytes exactly',()=>{
 assert.equal(Buffer.byteLength(skill),9399);
 assert.equal(sha(skill),'1e16bc616683136a67ff64ba81b27db7e87412d321377a3838463f28f97b7e8c');
 assert.equal(sha(source),'58a3e5c1479e8b4e0f944ada48f686337e1f116d335061f202ffeb1e59ca1b6f');
 assert.match(skill,/^---\nname: ci-failure-triage-v5\n/);
 assert.match(skill,/HYPOTHESES: NOT\\_SUPPORTED/);
 assert.match(skill,/SINGLE\\_CAUSE/);
 assert.match(skill,/FIX\\_HEAD/);
});
test('trial candidate cannot appear to be production qualified or have consented access',()=>{
 assert.match(skill,/NOT a qualified or host-tested skill/);
 assert.match(skill,/not authorization to install or run tools/);
 assert.match(skill,/Missing provenance, rights, source freshness or permissions require refusal/);
 assert.match(provenance,/development trial only/);
 assert.ok(provenance.includes('**not** a rights-qualified, production-installed'));
 assert.ok(provenance.includes('template-based **starter-draft**'));
 assert.match(provenance,/not.*automatically collect/i);
});
test('case set spans missing evidence, independent jobs, injection and fix-head identity',()=>{
 for(const name of ['A. Red status','B. Two simultaneously failing jobs',
  'C. Hostile text','D. Different failing and proposed repair','E. Unambiguous observed failure'])
   assert.ok(samples.includes(name),name);
 assert.match(samples,/Step-level log was not retained/);
 assert.match(samples,/Job: linux-build/);
 assert.match(samples,/Job: windows-test/);
 assert.match(samples,/SYSTEM OVERRIDE:/);
 assert.match(samples,/No pipeline has run on the proposed fix/);
 assert.match(samples,/not.*private logs/i);
});
test('public issue form demands observed outcome and warns about public disclosure',()=>{
 assert.match(issueForm,/name: External skill trial feedback/);
 assert.match(issueForm,/id: trial-path/);
 assert.match(issueForm,/id: host/);
 assert.match(issueForm,/id: outcome/);
 assert.match(issueForm,/Actual outcome/);
 assert.match(issueForm,/Do not paste secrets/);
 assert.match(issueForm,/required: true/);
 assert.match(provenance,/issues\/new\?template=skill-trial-feedback\.yml/);
});
