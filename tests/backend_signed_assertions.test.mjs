import test from 'node:test';
import assert from 'node:assert/strict';
import {createHash,generateKeyPairSync,sign as signEd25519} from 'node:crypto';
import {canonicalJSON,createComposer,verifyPackage} from '../src/backend/compose.mjs';
import {createSignedAssertionAdapter,AssertionRefusal} from '../src/backend/signed-assertions.mjs';

const SHA=x=>createHash('sha256').update(x).digest('hex');
const T=1784419200;
const DOMAIN='QORTARA-METHOD-ASSERTION-V1\n';
const {publicKey,privateKey}=generateKeyPairSync('ed25519');
const publicKeyPem=publicKey.export({type:'spki',format:'pem'}).toString('utf8');
const publicKeySha256=SHA(publicKey.export({type:'spki',format:'der'}));
const proofBytes={
 evidence:Buffer.from('static source review evidence, test fixture 01'),
 rights:Buffer.from('independent rights review fixture 02'),
 authority:Buffer.from('host authority permission fixture 03'),
 coverage:Buffer.from('outcome coverage fixture 04')
};
const proofDigests=Object.fromEntries(Object.entries(proofBytes).map(([k,b])=>[k,SHA(b)]));
const allTrue=()=>({evidence:true,rights:true,authority:true,coverage:true});
const trusted=()=>({
 schema:'qortara/method-assertion-trust/1',issuer:'fixture.issuer',
 keyId:'pilot-key-01',publicKeyPem,publicKeySha256,policyRevision:'policy.v1',
 revocations:{validFrom:T-3600,expiresAt:T+3600,proofDigests:[]}
});
const payload=(subjectSha256,opts={})=>{
 const facts={...allTrue(),...(opts.facts||{})};
 const evidenceDigests=Object.fromEntries(Object.keys(facts).map(k=>[k,facts[k]?proofDigests[k]:null]));
 return {schema:'qortara/method-assertion/1',subjectSha256,issuer:'fixture.issuer',
  keyId:'pilot-key-01',policyRevision:'policy.v1',validFrom:T-60,expiresAt:T+60,
  facts,evidenceDigests,...(opts.overrides||{})};
};
const envelope=(p,key=privateKey)=>({schema:'qortara/signed-method-assertion/1',payload:p,
 signature:signEd25519(null,Buffer.from(DOMAIN+canonicalJSON(p),'utf8'),key).toString('base64url')});
const setup=({alterPayload,alterEnvelope,alterTrust,alterEvidence,now=T}={})=>{
 const subject='a'.repeat(64);let p=payload(subject);
 if(alterPayload)p=alterPayload(p);
 let e=envelope(p);
 if(alterEnvelope)e=alterEnvelope(e);
 const policy=trusted();
 if(alterTrust)alterTrust(policy,e);
 const read=({field})=>alterEvidence?alterEvidence(field,proofBytes[field]):proofBytes[field];
 const adapter=createSignedAssertionAdapter({trust:policy,
  loadEnvelope:async()=>e,readEvidence:async arg=>read(arg),nowEpoch:()=>now});
 return {adapter,subject,envelope:e,policy};
};
const rejected=code=>({code});
const method=()=>({id:'fixture-method',origin:'https://example.test/pinned-fixture',
 sourcePath:'docs/fixtures/method.txt',commit:'b'.repeat(40),
 methodVersion:'v1',methodText:'Check each change against the recorded test result.',
 sha256:SHA('Check each change against the recorded test result.'),
 covers:['changes reviewed'],containsAssets:false});
const recipe=()=>({schema:'qortara/internal-composition-plan/1',name:'review-changes',
 title:'Review changes',description:'Check changes against test evidence.',
 targetHost:'offline-fixture',requiredOutcomes:['changes reviewed'],
 network:false,secrets:false,execution:false});
const holo='c'.repeat(64);
const prism=x=>({
 schema:'qortara/local-eligibility-result/1',application:'Qortara Skills Eligibility',
 artifact:{sha256:holo},status:'GUEST_COMPLETED',engine:'prism-code@0.9.5',
 requestHex:x.requestHex,exitCode:0,productionEligible:false,
 response:x.requestHex==='01010101'?'eligible':'refused: RIGHTS_UNRESOLVED',
 responseHex:Buffer.from(x.requestHex==='01010101'?'eligible':'refused: RIGHTS_UNRESOLVED').toString('hex')
});

test('valid pinned Ed25519 assertion authenticates exact subject and evidence bytes',async()=>{
 const {adapter,subject}=setup();
 const result=await adapter({subjectSha256:subject});
 assert.equal(result.subjectSha256,subject);
 assert.equal(result.issuer,'fixture.issuer');
 assert.match(result.proofDigest,/^[0-9a-f]{64}$/);
 assert.deepEqual([result.evidence,result.rights,result.authority,result.coverage],[true,true,true,true]);
});
test('trusted signature assertions integrate into composer, still development only',async()=>{
 // The signed record is fixed to the specific subject generated by the
 // composer; test issuer signs at lookup time solely as a fixture.
 const trust=trusted();
 const assertMethod=createSignedAssertionAdapter({trust,
  loadEnvelope:async subjectSha256=>envelope(payload(subjectSha256)),
  readEvidence:async({field})=>proofBytes[field],nowEpoch:()=>T});
 const p=await createComposer({assertMethod,runPrism:prism,holoSha256:holo})(recipe(),[method()]);
 assert.equal(verifyPackage(p).state,'INTEGRITY_VERIFIED');
 const receipt=JSON.parse(p.files['RECEIPT.json']);
 assert.equal(receipt.assertions.length,1);
 assert.equal(receipt.assertions[0].issuer,'fixture.issuer');
 assert.equal(receipt.productionEligible,false);
});
test('a signed denial reaches Prism as a refusal, never becomes a package',async()=>{
 const trust=trusted();let seen='';
 const adapter=createSignedAssertionAdapter({trust,
  loadEnvelope:async subjectSha256=>envelope(payload(subjectSha256,{facts:{rights:false}})),
  readEvidence:async({field})=>proofBytes[field],nowEpoch:()=>T});
 const runPrism=x=>{seen=x.requestHex;return prism(x);};
 await assert.rejects(createComposer({assertMethod:adapter,runPrism,holoSha256:holo})(recipe(),[method()]),
   rejected('PRISM_REFUSED'));
 assert.equal(seen,'01000101');
});
test('tampering the signed facts refuses',async()=>{
 const {adapter,subject}=setup({alterEnvelope:e=>({...e,payload:{
  ...e.payload,facts:{...e.payload.facts,rights:false},
  evidenceDigests:{...e.payload.evidenceDigests,rights:null}}})});
 await assert.rejects(adapter({subjectSha256:subject}),rejected('BAD_SIGNATURE'));
});
test('signature from another Ed25519 key refuses',async()=>{
 const {privateKey:other}=generateKeyPairSync('ed25519');
 const {adapter,subject}=setup({alterEnvelope:e=>envelope(e.payload,other)});
 await assert.rejects(adapter({subjectSha256:subject}),rejected('BAD_SIGNATURE'));
});
test('wrong subject cannot borrow another plan proof',async()=>{
 const {adapter}=setup();
 await assert.rejects(adapter({subjectSha256:'d'.repeat(64)}),rejected('ASSERTION_SCOPE'));
});
test('changed authority policy revision refuses even with signature',async()=>{
 const {adapter,subject}=setup({alterPayload:p=>({...p,policyRevision:'policy.v2'})});
 await assert.rejects(adapter({subjectSha256:subject}),rejected('ASSERTION_SCOPE'));
});
test('expired signed assertion refuses',async()=>{
 const {adapter,subject}=setup({now:T+100});
 await assert.rejects(adapter({subjectSha256:subject}),rejected('ASSERTION_EXPIRED'));
});
test('not-yet-valid signed assertion refuses',async()=>{
 const {adapter,subject}=setup({now:T-100});
 await assert.rejects(adapter({subjectSha256:subject}),rejected('ASSERTION_EXPIRED'));
});
test('stale signed revocation trust list refuses before reading claim',async()=>{
 const {adapter,subject}=setup({now:T+4000});
 await assert.rejects(adapter({subjectSha256:subject}),rejected('REVOCATIONS_STALE'));
});
test('revoked exact signed proof digest refuses',async()=>{
 const {adapter,subject}=setup({alterTrust:(t,e)=>{
  t.revocations.proofDigests.push(SHA(Buffer.from(canonicalJSON(e),'utf8')));
 }});
 await assert.rejects(adapter({subjectSha256:subject}),rejected('ASSERTION_REVOKED'));
});
test('false evidence digest cannot authenticate different bytes',async()=>{
 const {adapter,subject}=setup({alterEvidence:(field,bytes)=>field==='rights'?Buffer.from('tampered'):bytes});
 await assert.rejects(adapter({subjectSha256:subject}),rejected('EVIDENCE_MISMATCH'));
});
test('unknown evidence bytes never default to trust',async()=>{
 const {adapter,subject}=setup({alterEvidence:(field,bytes)=>field==='rights'?null:bytes});
 await assert.rejects(adapter({subjectSha256:subject}),rejected('EVIDENCE_MISSING'));
});
test('unrecognized fields in signed payload refuse even if signed',async()=>{
 const {adapter,subject}=setup({alterPayload:p=>({...p,extraAuthorization:true})});
 await assert.rejects(adapter({subjectSha256:subject}),rejected('BAD_ASSERTION'));
});
test('missing one claimed evidence digest refuses even if signed',async()=>{
 const {adapter,subject}=setup({alterPayload:p=>({...p,evidenceDigests:{...p.evidenceDigests,rights:null}})});
 await assert.rejects(adapter({subjectSha256:subject}),rejected('BAD_ASSERTION'));
});
test('noncanonical signature encoding refuses',async()=>{
 const {adapter,subject}=setup({alterEnvelope:e=>({...e,signature:e.signature+'='})});
 await assert.rejects(adapter({subjectSha256:subject}),rejected('BAD_SIGNATURE'));
});
test('trust root cannot be silently replaced or use a non-Ed25519 public key',()=>{
 const bad=trusted();bad.publicKeySha256='0'.repeat(64);
 assert.throws(()=>createSignedAssertionAdapter({trust:bad,loadEnvelope:()=>{},readEvidence:()=>{}}),rejected('TRUST_CONFIG'));
});
test('unsigned or absent trusted claim refuses',async()=>{
 const {subject}=setup();
 const adapter=createSignedAssertionAdapter({trust:trusted(),loadEnvelope:async()=>null,
 readEvidence:async()=>null,nowEpoch:()=>T});
 await assert.rejects(adapter({subjectSha256:subject}),rejected('BAD_ASSERTION'));
});
