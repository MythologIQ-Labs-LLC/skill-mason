def body(name: str, spec: dict) -> str:
    skill = (HERE / "skills" / name / "SKILL.md").read_text(encoding="utf-8").rstrip("\n")
    assert "````" not in skill, "the skill must not contain a four-backtick fence"
    return (
        "### Submitted by\n\nAI agent\n\n"
        "### Component\n\ndocs\n\n"
        f"### Problem\n\n{spec['problem']}\n\n{OBSERVED}\n\n"
        "### Proposed API or behavior\n\n"
        f"Add `skills/{name}/SKILL.md` beside the existing `skills/prism/SKILL.md`, with this content. "
        "It is offered as a starting point: please correct anything that does not match the toolchain you intend to ship, "
        "and prefer your own wording for release status.\n\n"
        f"````markdown\n{skill}\n````\n\n"
        f"### Acceptance test\n\n```text\n{spec['acceptance']}\n```\n\n"
        f"### Current workaround\n\n{spec['workaround']}\n\n"
        "### Searched existing requests\n\n"
        "- [ ] I searched /docs/requests.md and the open issues, and no existing request covers this.\n\n"
        "The open and closed issues of this repository were searched on 2026-11-17 for skill, agent, audit, "
        "negative control, model-first, pin drift and `available_in`. The only related request found is #353 "
        "(closed), which shipped the existing `prism` skill; #718 covers the documentation side of the version "
        "boundary. The rendered `/docs/requests.md` page was not reachable from the submitting environment, so "
        "the box above is left for the person filing to tick after reading it."
        f"{FOOTER}"
    )


def main() -> None:
    for name, spec in ISSUES.items():
        (HERE / f"{name}.issue.md").write_text(body(name, spec), encoding="utf-8", newline="\n")
        (HERE / f"{name}.title.txt").write_text(spec["title"] + "\n", encoding="utf-8", newline="\n")
        print(f"wrote {name}.issue.md")


if __name__ == "__main__":
    main()
